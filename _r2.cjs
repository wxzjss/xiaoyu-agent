const fs = require("fs");
const lines = [
'/**',
' * 【输入法那套已经删了 —— 这个脚本改成守「不许放回来」】',
' *',
' * 来历：2026-11-07 主人发截图，输入框上方卡着一块白框（微软拼音的 composition 预编辑串）。',
' * 当时修法是加一整套「打字/刚上屏时别抢焦点、别切 IME」。',
' *',
' * 2026-11-08 主人说：「把小鱼Agent 有关输入法的修改全删了」—— 不是停用，是真删。',
' * 已在 commit e5bee55 里从 index.html 和 electron/main.cjs 两边删干净。',
' *',
' * 于是本脚本反过来守：这些名字一个都不许在代码里出现（注释里提名字不算）。',
' * 哪天有人把停用的那套又接回去，这里会立刻红。',
' */',
'import { makeChecker } from "./_harness_util.mjs";',
'import fs from "node:fs";',
'',
'const t = makeChecker("ui / 输入法那套已删");',
'const html = fs.readFileSync("public/index.html", "utf8");',
'const mainSrc = fs.readFileSync("electron/main.cjs", "utf8");',
'',
'/* 去掉注释行：注释里提到这些名字是为了说明来历，不算「代码里还有」。 */',
'const stripComments = (src) =>',
'  src',
'    .split(/\\r?\\n/)',
'    .filter((l) => {',
'      const s = l.trim();',
'      return s && !s.startsWith("//") && !s.startsWith("*") && !s.startsWith("/*");',
'    })',
'    .join("\\n");',
'const code = stripComments(html);',
'',
'const GONE = [',
'  ["imeBusy", "imeBusy"],',
'  ["imeSwitching", "imeSwitching"],',
'  ["imeFeatureOn", "imeFeatureOn"],',
'  ["imeMatchOnce", "imeMatchOnce"],',
'  ["imeMatchSoon", "imeMatchSoon"],',
'  ["imeCancelSoon", "imeCancelSoon"],',
'  ["imeTypingRecently", "imeTypingRecently"],',
'  ["imePrimeOnBoot", "imePrimeOnBoot"],',
'  ["markTyping", "markTyping"],',
'  ["_imeUserTouchedAt", "_imeUserTouchedAt"],',
'  ["__xyImeComposing", "__xyImeComposing"],',
'  ["__xyImeEndAt", "__xyImeEndAt"],',
'  ["__xyImeTypeAt", "__xyImeTypeAt"],',
'  ["切输入法的 IPC（ime:matchSystem）", "ime:matchSystem"],',
'];',
'for (const [name, needle] of GONE) {',
'  t.ok("已删干净：" + name, !code.includes(needle));',
'}',
'',
't.ok("主进程也不许再有好中英方向（wantZh）", !stripComments(mainSrc).includes("wantZh"));',
'',
'/* 输入框本身还在 —— 删的是那套，不是把输入框删了 */',
't.ok("输入框还在", /id="input"/.test(html) || /querySelector\\(.textarea.\\)/.test(html));',
't.ok("发消息还在", /sendBtn|syncSendBtn|发送/.test(html));',
'',
'if (process.env.SKIP_UI) t.done();',
].join("\n");
fs.writeFileSync("scripts/check-ime-compose.mjs", lines + "\n", "utf8");
console.log("写好 " + lines.length + " 字符");
