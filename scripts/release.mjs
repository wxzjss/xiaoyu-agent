function readToken() {
  if (process.env.GITHUB_TOKEN) return process.env.GITHUB_TOKEN.trim();
  const cands = [
    join(homedir(), 'GitHub仓库', 'ghp.txt'),
    'C:\\GitHub仓库\\ghp.txt',
  ];
  for (const f of cands) {
    if (!existsSync(f)) continue;
    const m = readFileSync(f, 'utf8').match(/gh[pousr]_[A-Za-z0-9]{20,}/);
    if (m) return m[0];
  }
  return null;
}

